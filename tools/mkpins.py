"""Write the loader's pinned-digest header (loader/pins.h's contents) from a list of SHA-256s.

  mkpins.py [LIST] -o OUT.h

LIST: one hex SHA-256 per line ('#' comments, blank lines and anything after the digest on a
line are ignored; `sha256sum` output works). No LIST, or an empty one: no pins, and the loader
accepts any payload whose own header digest matches (integrity only). With pins it starts only
payloads whose digest is listed: the project's own trust list for what this loader may start.
"""
import argparse
import re
import sys


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("list", nargs="?")
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()
    digests = []
    if a.list:
        for n, line in enumerate(open(a.list), 1):
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            word = line.split()[0].lower()
            if not re.fullmatch(r"[0-9a-f]{64}", word):
                sys.exit(f"mkpins: {a.list}:{n}: not a SHA-256: {word!r}")
            digests.append(word)
    rows = ["\t{ " + ", ".join(f"0x{d[i:i + 2]}" for i in range(0, 64, 2)) + " }," for d in digests]
    with open(a.out, "w") as f:
        f.write("/* Generated by tools/mkpins.py: the digests this loader accepts (none: any). */\n")
        f.write("#include <stdint.h>\n")
        f.write(f"#define LDR_NPINS {len(digests)}u\n")
        f.write(f"static const uint8_t ldr_pins[{max(1, len(digests))}][32] = {{\n")
        f.write("\n".join(rows) if rows else "\t{ 0 },")
        f.write("\n};\n")
    print(f"mkpins: {len(digests)} pinned digest(s) -> {a.out}")


if __name__ == "__main__":
    main()
